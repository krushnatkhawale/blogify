package io.github.blogify.core.generator;

import io.github.blogify.core.model.BlogCodeBlockModel;
import io.github.blogify.core.model.BlogPostModel;
import io.github.blogify.core.model.BlogSectionModel;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.LocalDate;
import java.util.ArrayList;
import java.util.List;

/**
 * Generates Jekyll-compatible Markdown files and configuration for native GitHub Pages hosting.
 */
public class JekyllGenerator {

    public List<Path> generate(File outputDir, String siteTitle, List<BlogPostModel> posts) throws IOException {
        return generate(outputDir, siteTitle, posts, false);
    }

    public List<Path> generate(File outputDir, String siteTitle, List<BlogPostModel> posts, boolean includeDrafts) throws IOException {
        List<Path> writtenFiles = new ArrayList<>();

        Path outPath = outputDir.toPath();
        Files.createDirectories(outPath);

        List<BlogPostModel> publishablePosts = new ArrayList<>();
        for (BlogPostModel post : posts) {
            if (includeDrafts || !post.isDraft()) {
                publishablePosts.add(post);
            }
        }

        // 1. _config.yml
        String configTitle = (siteTitle != null && !siteTitle.isBlank()) ? siteTitle : "Project Blog";
        String configYaml = buildConfigFile(configTitle);
        Path configFile = outPath.resolve("_config.yml");
        Files.writeString(configFile, configYaml, StandardCharsets.UTF_8);
        writtenFiles.add(configFile);

        // 2. index.md
        String indexContent = buildIndexFile(configTitle, publishablePosts);
        Path indexFile = outPath.resolve("index.md");
        Files.writeString(indexFile, indexContent, StandardCharsets.UTF_8);
        writtenFiles.add(indexFile);

        // 3. _posts/ directory
        Path postsDir = outPath.resolve("_posts");
        Files.createDirectories(postsDir);

        for (BlogPostModel post : publishablePosts) {
            String date = normalizeDate(post.getDate());
            String filename = date + "-" + post.getSlug() + ".md";
            Path postFile = postsDir.resolve(filename);

            String postMarkdown = buildPostMarkdown(post, date);
            Files.writeString(postFile, postMarkdown, StandardCharsets.UTF_8);
            writtenFiles.add(postFile);
        }

        return writtenFiles;
    }

    private String buildConfigFile(String title) {
        return """
                # GitHub Pages / Jekyll Configuration generated by Blogify
                title: "%s"
                description: "Automated technical blog generated directly from application source code at compile time."
                theme: minima
                markdown: kramdown
                plugins:
                  - jekyll-feed
                """.formatted(escapeYaml(title));
    }

    private String buildIndexFile(String siteTitle, List<BlogPostModel> posts) {
        StringBuilder sb = new StringBuilder();
        sb.append("---\n");
        sb.append("layout: home\n");
        sb.append("title: \"").append(escapeYaml(siteTitle)).append("\"\n");
        sb.append("---\n\n");

        sb.append("# ").append(siteTitle).append("\n\n");
        sb.append("Welcome! This technical blog is automatically generated from application source code at compile time.\n\n");

        if (posts.isEmpty()) {
            sb.append("*No blog posts found. Add markdown posts in `blogs/` to generate posts.*\n");
            return sb.toString();
        }

        sb.append("## Articles\n\n");
        for (BlogPostModel post : posts) {
            String date = normalizeDate(post.getDate());
            String year = date.substring(0, 4);
            String month = date.substring(5, 7);
            String day = date.substring(8, 10);
            String permalink = "/" + year + "/" + month + "/" + day + "/" + post.getSlug() + ".html";

            sb.append("### [").append(post.getTitle()).append("](").append(permalink).append(")");
            if (post.isRetired()) {
                sb.append(" `[RETIRED]`");
            }
            sb.append("\n\n");

            List<String> metaParts = new ArrayList<>();
            if (!post.getDate().isBlank()) {
                metaParts.add(post.getDate());
            }
            if (!post.getAuthor().isBlank()) {
                metaParts.add("by " + post.getAuthor());
            }
            if (!post.getVersion().isBlank() || !post.getCommitSha().isBlank()) {
                String src = "Source: ";
                if (!post.getVersion().isBlank()) src += post.getVersion();
                if (!post.getCommitSha().isBlank()) {
                    if (!post.getVersion().isBlank()) src += " · ";
                    src += "commit " + post.getCommitSha();
                }
                metaParts.add(src);
            }

            if (!metaParts.isEmpty()) {
                sb.append("*").append(String.join(" • ", metaParts)).append("*\n\n");
            }

            if (!post.getDescription().isBlank()) {
                sb.append(post.getDescription()).append("\n\n");
            }

            if (!post.getTags().isEmpty()) {
                sb.append("**Tags:** ");
                sb.append(String.join(", ", post.getTags().stream().map(t -> "`" + t + "`").toList()));
                sb.append("\n\n");
            }

            sb.append("---\n\n");
        }

        return sb.toString();
    }

    private String buildPostMarkdown(BlogPostModel post, String date) {
        StringBuilder sb = new StringBuilder();

        // YAML Frontmatter for Jekyll
        sb.append("---\n");
        sb.append("layout: post\n");
        sb.append("title: \"").append(escapeYaml(post.getTitle())).append("\"\n");
        sb.append("slug: \"").append(escapeYaml(post.getSlug())).append("\"\n");
        sb.append("date: ").append(date).append("\n");
        if (!post.getAuthor().isBlank()) {
            sb.append("author: \"").append(escapeYaml(post.getAuthor())).append("\"\n");
        }
        if (!post.getDescription().isBlank()) {
            sb.append("description: \"").append(escapeYaml(post.getDescription())).append("\"\n");
        }
        sb.append("draft: ").append(post.isDraft()).append("\n");
        if (!post.getTags().isEmpty()) {
            sb.append("tags:\n");
            for (String tag : post.getTags()) {
                sb.append("  - \"").append(escapeYaml(tag)).append("\"\n");
            }
        }
        if (!post.getVersion().isBlank()) {
            sb.append("version: \"").append(escapeYaml(post.getVersion())).append("\"\n");
        }
        if (!post.getCommitSha().isBlank()) {
            sb.append("commit: \"").append(escapeYaml(post.getCommitSha())).append("\"\n");
        }
        if (!post.getStatus().isBlank()) {
            sb.append("status: \"").append(escapeYaml(post.getStatus())).append("\"\n");
        }
        sb.append("---\n\n");

        // Subtitle line (Author, Date, Source Version)
        List<String> metaParts = new ArrayList<>();
        if (!post.getAuthor().isBlank()) {
            metaParts.add("By " + post.getAuthor());
        }
        if (!date.isBlank()) {
            metaParts.add("Published on " + date);
        }
        if (!post.getVersion().isBlank() || !post.getCommitSha().isBlank()) {
            String srcBadge = "Source: ";
            if (!post.getVersion().isBlank()) srcBadge += post.getVersion();
            if (!post.getCommitSha().isBlank()) {
                if (!post.getVersion().isBlank()) srcBadge += " · ";
                if (!post.getRepoUrl().isBlank()) {
                    srcBadge += "[" + post.getCommitSha() + "](" + post.getRepoUrl() + "/commit/" + post.getCommitSha() + ")";
                } else {
                    srcBadge += "commit " + post.getCommitSha();
                }
            }
            metaParts.add(srcBadge);
        }
        if (!metaParts.isEmpty()) {
            sb.append("> *").append(String.join(" | ", metaParts)).append("*\n\n");
        }

        // Retired / Deprecated Notice
        if (post.isRetired()) {
            sb.append("> [!WARNING]\n");
            sb.append("> **This architecture guide has been retired.**\n");
            if (!post.getSupersededMessage().isBlank()) {
                sb.append("> ").append(post.getSupersededMessage()).append("\n");
            }
            if (!post.getSupersededBy().isBlank()) {
                sb.append("> [Read updated guide: ").append(post.getSupersededBy()).append("](").append(post.getSupersededBy()).append(".html)\n");
            }
            sb.append("\n");
        }

        // Problem & Insight Callout Cards
        if (!post.getProblem().isBlank()) {
            sb.append("> [!NOTE]\n");
            sb.append("> **The Problem**: ").append(post.getProblem()).append("\n\n");
        }

        if (!post.getInsight().isBlank()) {
            sb.append("> [!TIP]\n");
            sb.append("> **The Key Insight**: ").append(post.getInsight()).append("\n\n");
        }

        // Visual Architecture Flow
        if (!post.getDiagram().isBlank()) {
            sb.append("### Architecture Flow\n\n");
            String dia = post.getDiagram().trim();
            if (dia.startsWith("http://") || dia.startsWith("https://") || dia.endsWith(".png") || dia.endsWith(".svg") || dia.endsWith(".jpg")) {
                sb.append("![").append(post.getTitle()).append(" Architecture](").append(dia).append(")\n\n");
            } else {
                sb.append("```mermaid\n").append(dia).append("\n```\n\n");
            }
        }

        // Intro Javadoc Content
        if (!post.getIntroContent().isBlank()) {
            sb.append(post.getIntroContent()).append("\n\n");
        }

        // Raw body if available
        if (!post.getRawBody().isBlank()) {
            sb.append(post.getRawBody()).append("\n\n");
        }

        // Standalone code blocks
        for (BlogCodeBlockModel cb : post.getStandaloneCodeBlocks()) {
            appendCodeBlock(sb, cb);
        }

        // Sections
        for (BlogSectionModel section : post.getSections()) {
            sb.append("## ").append(section.getHeading()).append("\n\n");
            if (!section.getContent().isBlank()) {
                sb.append(section.getContent()).append("\n\n");
            }
            for (BlogCodeBlockModel cb : section.getCodeBlocks()) {
                appendCodeBlock(sb, cb);
            }
        }

        // Key Takeaways
        if (!post.getTakeaways().isEmpty()) {
            sb.append("### Key Takeaways\n\n");
            for (String t : post.getTakeaways()) {
                sb.append("- ").append(t).append("\n");
            }
            sb.append("\n");
        }

        return sb.toString();
    }

    private void appendCodeBlock(StringBuilder sb, BlogCodeBlockModel cb) {
        if (!cb.getDescription().isBlank()) {
            sb.append("**").append(cb.getDescription()).append("**\n\n");
        }
        sb.append("```").append(cb.getLanguage()).append("\n");
        sb.append(cb.getCode()).append("\n");
        sb.append("```\n\n");

        if (cb.hasFullCode()) {
            sb.append("<details>\n");
            sb.append("<summary>🔍 View Full Implementation (").append(cb.getDescription().isBlank() ? "Code" : cb.getDescription()).append(")</summary>\n\n");
            sb.append("```").append(cb.getLanguage()).append("\n");
            sb.append(cb.getFullCode()).append("\n");
            sb.append("```\n\n");
            sb.append("</details>\n\n");
        }
    }

    private String normalizeDate(String date) {
        if (date != null && date.matches("^\\d{4}-\\d{2}-\\d{2}$")) {
            return date;
        }
        return LocalDate.now().toString();
    }

    private String escapeYaml(String s) {
        if (s == null) {
            return "";
        }
        return s.replace("\"", "\\\"");
    }
}
